function recalcHouseAggregate(stu,hId){
  const results=(DB.g('student_pretest_sets')||[]).filter(r=>r.stu===stu&&r.hId===hId);
  if(!results.length)return;
  const avg=Math.round(results.reduce((s,r)=>s+r.score,0)/results.length);
  const pts=DB.g('student_pretests')||[];
  const idx=pts.findIndex(p=>p.stu===stu&&p.hId===hId);
  if(idx>=0)pts[idx]={stu,hId,score:avg,status:'completed'};
  else pts.push({stu,hId,score:avg,status:'completed'});
  DB.s('student_pretests',pts);
}

